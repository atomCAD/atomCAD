/// A failure inside a custom network surfaces in the *using* network as a
/// derived entry on the instance, whose root addresses the offending node
/// **inside the child** — and that root joins the list as its own top-level row
/// with a provenance qualifier, so the collapse parent is always present.
#[test]
fn cross_network_root_cause_is_addressed_in_the_child() {
    let mut designer = StructureDesigner::new();
    designer.add_node_network("child");
    designer.set_active_node_network_name(Some("child".to_string()));
    let child_expr = add_expr(&mut designer, "x + 1", &["x"]); // fails inside the child
    assert!(designer.set_return_node_id(Some(child_expr)));
    validate_and_refresh(&mut designer);

    designer.add_node_network("main");
    designer.set_active_node_network_name(Some("main".to_string()));
    let instance = designer.add_node("child", DVec2::ZERO);
    designer.set_node_display(instance, true);
    validate_and_refresh(&mut designer);

    let errors = errors_of(&designer, "main");

    // The instance is derived — its boundary link points into the child.
    let instance_row = row_for_node(&errors, instance, APIErrorSource::Evaluation);
    let root = instance_row
        .root_cause
        .as_ref()
        .expect("the instance's error is derived from the child's failure");
    assert_eq!(root.host_network, "child");
    assert_eq!(root.node_id, child_expr);
    assert!(root.scope_path.is_empty());

    // ...and the root itself is listed once, addressed in the child.
    let roots = top_level_rows(&errors);
    assert_eq!(
        roots.len(),
        1,
        "one problem ⇒ one top-level row; got {:?}",
        roots
            .iter()
            .map(|e| (&e.host_network, e.node_id, &e.error_text))
            .collect::<Vec<_>>()
    );
    assert_eq!(roots[0].host_network.as_deref(), Some("child"));
    assert_eq!(roots[0].node_id, Some(child_expr));
    assert_eq!(
        roots[0].body_qualifier.as_deref(),
        Some("in child"),
        "a cross-network row names its host network as provenance"
    );

    // "Go to root cause" on the instance resolves to the same address.
    let jump = rust_lib_flutter_cad::api::structure_designer::view_builders::get_node_root_cause(
        &designer,
        &[],
        instance,
    )
    .expect("the instance has a navigable root cause");
    assert_eq!(jump.host_network, "child");
    assert_eq!(jump.node_id, child_expr);
    assert!(!jump.node_label.is_empty());
}

/// Renaming a network rewrites the network names embedded in stored jump
/// addresses (D6 key lifecycle): the long-lived snapshot outlives the refresh
/// that produced it, so a stale name would jump nowhere.
#[test]
fn rename_rewrites_stored_root_cause_host_network() {
    let mut designer = StructureDesigner::new();
    designer.add_node_network("child");
    designer.set_active_node_network_name(Some("child".to_string()));
    let child_expr = add_expr(&mut designer, "x + 1", &["x"]);
    assert!(designer.set_return_node_id(Some(child_expr)));
    validate_and_refresh(&mut designer);

    designer.add_node_network("main");
    designer.set_active_node_network_name(Some("main".to_string()));
    let instance = designer.add_node("child", DVec2::ZERO);
    designer.set_node_display(instance, true);
    validate_and_refresh(&mut designer);

    // Leave "main" so its rows come from the long-lived snapshot, then rename
    // the network its addresses point at.
    designer.add_node_network("other");
    designer.set_active_node_network_name(Some("other".to_string()));
    validate_and_refresh(&mut designer);
    assert!(designer.rename_node_network("child", "kid"));

    let errors = errors_of(&designer, "main");
    let roots = top_level_rows(&errors);
    assert_eq!(
        roots.len(),
        1,
        "the cross-network row survives the rename (its host was rewritten)"
    );
    assert_eq!(roots[0].host_network.as_deref(), Some("kid"));
    assert_eq!(
        row_for_node(&errors, instance, APIErrorSource::Evaluation)
            .root_cause
            .as_ref()
            .map(|r| r.host_network.clone()),
        Some("kid".to_string()),
        "the derived row's root pointer follows the rename too"
    );
}

