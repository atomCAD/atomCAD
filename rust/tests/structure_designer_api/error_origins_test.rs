//! Phase 5 of `doc/design_error_management.md` (D7) — root-cause origin links.
//!
//! Whenever a resolved wire value is an `Error`, the evaluator records an
//! **origin link** for the consumer: the jump-ready global address of the node
//! the error came from. An errored node with no link is a **root cause**; every
//! other errored node is *derived* and collapses behind its root in the panel,
//! so one failure produces one row instead of one row per node in its
//! downstream cone. Links cross custom-network boundaries (the two wrap sites
//! record the boundary hop explicitly), are pass-scoped (regenerated by every
//! refresh), and — where they are copied into a long-lived snapshot — follow
//! D6's key lifecycle when a network is renamed.

use atomcad_structure_designer::data_type::DataType;
use atomcad_structure_designer::eval_errors::{ErrorAddress, ErrorOrigin};
use atomcad_structure_designer::evaluator::network_evaluator::{
    NetworkEvaluationContext, NetworkEvaluator, NetworkStackElement,
};
use atomcad_structure_designer::node_network::{NodeRef, ValidationError};
use atomcad_structure_designer::nodes::expr::{ExprData, ExprParameter};
use atomcad_structure_designer::structure_designer::StructureDesigner;
use glam::f64::DVec2;
use rust_lib_flutter_cad::api::structure_designer::structure_designer_api_types::{
    APIErrorSource, APINetworkWithValidationErrors, APIValidationError,
};

// ============================================================================
// Helpers
// ============================================================================

fn setup_designer_with_network(network_name: &str) -> StructureDesigner {
    let mut designer = StructureDesigner::new();
    designer.add_node_network(network_name);
    designer.set_active_node_network_name(Some(network_name.to_string()));
    designer
}

fn full_refresh(designer: &mut StructureDesigner) {
    designer.mark_full_refresh();
    let changes = designer.get_pending_changes();
    designer.refresh(&changes);
}

fn validate_and_refresh(designer: &mut StructureDesigner) {
    designer.validate_active_network();
    full_refresh(designer);
}

/// Add an `expr` node to the **active** network with the given expression and
/// parameter names (all `Int`). A parameter left unwired makes the node fail at
/// runtime with a clean localized "missing input" error — the canonical root
/// cause used throughout this file.
fn add_expr(designer: &mut StructureDesigner, expression: &str, params: &[&str]) -> u64 {
    let id = designer.add_node_scoped(&[], "expr", DVec2::ZERO, None);
    set_expr_data(designer, &[], id, expression, params);
    id
}

fn set_expr_data(
    designer: &mut StructureDesigner,
    scope_path: &[u64],
    node_id: u64,
    expression: &str,
    params: &[&str],
) {
    let mut data = ExprData {
        parameters: params
            .iter()
            .map(|name| ExprParameter {
                id: None,
                name: name.to_string(),
                data_type: DataType::Int,
                data_type_str: None,
            })
            .collect(),
        expression: expression.to_string(),
        expr: None,
        error: None,
        output_type: None,
    };
    let _ = data.parse_and_validate(0);
    designer.set_node_network_data_scoped(scope_path, node_id, Box::new(data));
}

/// The unified error list of one network (`APIValidationError` is not `Clone`,
/// so the entry is taken by value out of the freshly built list).
fn errors_of(designer: &StructureDesigner, network_name: &str) -> Vec<APIValidationError> {
    let networks: Vec<APINetworkWithValidationErrors> =
        rust_lib_flutter_cad::api::structure_designer::view_builders::get_node_networks_with_errors(
            designer,
        );
    networks
        .into_iter()
        .find(|n| n.name == network_name)
        .unwrap_or_else(|| panic!("network '{network_name}' present in the error list"))
        .validation_errors
}

/// The rows the panel lists at top level: everything that is not a *derived*
/// entry (derived rows collapse behind their root's row).
fn top_level_rows(errors: &[APIValidationError]) -> Vec<&APIValidationError> {
    errors.iter().filter(|e| e.root_cause.is_none()).collect()
}

fn row_for_node<'a>(
    errors: &'a [APIValidationError],
    node_id: u64,
    source: APIErrorSource,
) -> &'a APIValidationError {
    errors
        .iter()
        .find(|e| e.node_id == Some(node_id) && e.source == source)
        .unwrap_or_else(|| {
            panic!(
                "no {:?} row for node {}; rows: {:?}",
                source,
                node_id,
                errors
                    .iter()
                    .map(|e| (e.node_id, e.source, &e.error_text))
                    .collect::<Vec<_>>()
            )
        })
}

