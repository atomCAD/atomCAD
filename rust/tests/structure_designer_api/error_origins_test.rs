/// Links are pass-scoped: a second refresh regenerates them (no accumulation),
/// and fixing the root cause clears the whole chain — root row and derived
/// entries alike — in one step.
#[test]
fn links_are_regenerated_by_every_pass() {
    let mut designer = setup_designer_with_network("main");
    let head = add_expr(&mut designer, "x + 1", &["x"]);
    let tail = add_expr(&mut designer, "z + 1", &["z"]);
    designer.connect_nodes(head, 0, tail, 0);
    designer.set_node_display(tail, true);
    validate_and_refresh(&mut designer);

    let before = errors_of(&designer, "main").len();
    full_refresh(&mut designer);
    assert_eq!(
        errors_of(&designer, "main").len(),
        before,
        "a second pass replaces the links, it does not accumulate them"
    );

    // Fix the root cause → the entire chain clears.
    set_expr_data(&mut designer, &[], head, "1 + 1", &[]);
    validate_and_refresh(&mut designer);
    assert!(
        errors_of(&designer, "main").is_empty(),
        "fixing the root clears the root row and every derived entry"
    );
}
