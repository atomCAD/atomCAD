/// One link **per distinct failing input**, in input-pin order, deduped by
/// address. A single-slot value would silently lose chains: a consumer with two
/// independently errored inputs must keep a link to each. (Most nodes early-out
/// on their first errored input, so this contract is exercised directly against
/// `evaluate_arg` — the choke point that records it.)
#[test]
fn each_failing_input_records_its_own_link_in_pin_order() {
    let mut designer = setup_designer_with_network("main");
    let source_x = add_expr(&mut designer, "a + 1", &["a"]); // fails
    let source_y = add_expr(&mut designer, "b + 1", &["b"]); // fails
    let sink = add_expr(&mut designer, "x + y", &["x", "y"]);
    designer.connect_nodes(source_x, 0, sink, 0);
    designer.connect_nodes(source_y, 0, sink, 1);
    designer.validate_active_network();

    let registry = &designer.node_type_registry;
    let network = registry.node_networks.get("main").unwrap();
    let evaluator = NetworkEvaluator::new();
    let mut context = NetworkEvaluationContext::new();
    let network_stack = vec![NetworkStackElement::root(network)];
    // Resolve both pins, as a node tolerating its first errored input would.
    for param_index in 0..2 {
        let _ = evaluator.evaluate_arg(&network_stack, sink, registry, &mut context, param_index);
    }
    // Re-resolving pin 0 must not add a second link for the same address.
    let _ = evaluator.evaluate_arg(&network_stack, sink, registry, &mut context, 0);

    let links = context
        .node_error_origins
        .get(&NodeRef::top(sink))
        .expect("the sink recorded its origins");
    assert_eq!(
        links
            .iter()
            .map(|link| link.address.node_id)
            .collect::<Vec<_>>(),
        vec![source_x, source_y],
        "one link per failing input, in input-pin order, deduped by address"
    );
    assert_eq!(links[0].source_ref, NodeRef::top(source_x));
    assert_eq!(links[0].address.host_network, "main");
}

/// A wire inside a zone body addresses its source with the **body's scope
/// path**: the address's `scope_path` is the chain of zone-body hops since the
/// last network hop, read off the live network stack (the only place that
/// distinguishes a body hop from a custom-network hop).
#[test]
fn body_wire_source_carries_the_body_scope_path() {
    let mut designer = setup_designer_with_network("main");
    let map_id = designer.add_node("map", DVec2::ZERO);
    let body_source = designer.add_node_scoped(&[map_id], "expr", DVec2::ZERO, None);
    set_expr_data(&mut designer, &[map_id], body_source, "a + 1", &["a"]);
    let body_sink = designer.add_node_scoped(&[map_id], "expr", DVec2::new(200.0, 0.0), None);
    set_expr_data(&mut designer, &[map_id], body_sink, "b + 1", &["b"]);
    designer.connect_nodes_scoped(&[map_id], body_source, 0, body_sink, 0);
    designer.validate_active_network();

    let registry = &designer.node_type_registry;
    let network = registry.node_networks.get("main").unwrap();
    let body = network.nodes[&map_id].zone.as_deref().unwrap();
    let evaluator = NetworkEvaluator::new();
    let mut context = NetworkEvaluationContext::new();
    context.push_eval_scope(map_id);
    let network_stack = vec![
        NetworkStackElement::root(network),
        NetworkStackElement::body_static(body, map_id),
    ];
    let _ = evaluator.evaluate_arg(&network_stack, body_sink, registry, &mut context, 0);

    let links = context
        .node_error_origins
        .get(&NodeRef::scoped(&[map_id], body_sink))
        .expect("the body sink recorded its origin");
    assert_eq!(
        links,
        &vec![ErrorOrigin {
            address: ErrorAddress {
                host_network: "main".to_string(),
                scope_path: vec![map_id],
                node_id: body_source,
            },
            source_ref: NodeRef::scoped(&[map_id], body_source),
        }],
        "a body wire's source is addressed inside the body, in its own network"
    );
}

