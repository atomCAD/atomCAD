/// A chain of three nodes whose head fails yields **one** top-level row (the
/// head) and two derived entries, each carrying the chain's root — so the panel
/// shows one problem, not its three symptoms. Each derived entry's link points
/// one hop upstream, which is what makes the walk to the root exact.
#[test]
fn chain_of_three_has_one_root_and_derived_entries() {
    let mut designer = setup_designer_with_network("main");
    let head = add_expr(&mut designer, "x + 1", &["x"]); // `x` left unwired → fails
    let middle = add_expr(&mut designer, "y + 1", &["y"]);
    let tail = add_expr(&mut designer, "z + 1", &["z"]);
    designer.connect_nodes(head, 0, middle, 0);
    designer.connect_nodes(middle, 0, tail, 0);
    designer.set_node_display(tail, true);
    validate_and_refresh(&mut designer);

    let errors = errors_of(&designer, "main");
    let roots = top_level_rows(&errors);
    assert_eq!(
        roots.len(),
        1,
        "one failure ⇒ one top-level row; got {:?}",
        roots
            .iter()
            .map(|e| (e.node_id, &e.error_text))
            .collect::<Vec<_>>()
    );
    assert_eq!(roots[0].node_id, Some(head));

    for derived_id in [middle, tail] {
        let row = row_for_node(&errors, derived_id, APIErrorSource::Evaluation);
        let root = row
            .root_cause
            .as_ref()
            .unwrap_or_else(|| panic!("node {derived_id} must be derived"));
        assert_eq!(root.node_id, head, "the walk ends at the chain's head");
        assert_eq!(root.host_network, "main");
        assert!(root.scope_path.is_empty());
        assert!(
            !root.error_text.is_empty(),
            "the root's own text travels with the link (transient landing surface)"
        );
    }
}

/// A derived chain routinely terminates at a **poisoned** node (blocking
/// validation error → skip-and-synthesize). The collapse parent is the *node*,
/// so the derived entries hang off its **validation** row; the synthesized eval
/// entry stays deduped away (D8) and no derived entry is left orphaned at top
/// level.
#[test]
fn poisoned_root_collapses_behind_its_validation_row() {
    let mut designer = setup_designer_with_network("main");
    let head = add_expr(&mut designer, "1 + 1", &[]);
    let middle = add_expr(&mut designer, "y + 1", &["y"]);
    designer.connect_nodes(head, 0, middle, 0);
    designer.set_node_display(middle, true);
    designer.validate_active_network();

    // Attribute a blocking validation error to the head (the shape any
    // cone-poisoning rule produces — e.g. a bare `relax`'s unresolved output).
    designer
        .node_type_registry
        .node_networks
        .get_mut("main")
        .unwrap()
        .validation_errors
        .push(ValidationError::new(
            "head is broken".to_string(),
            Some(head),
        ));
    full_refresh(&mut designer);

    let errors = errors_of(&designer, "main");
    let roots = top_level_rows(&errors);
    assert_eq!(
        roots.len(),
        1,
        "exactly one top-level row: the poisoned node's validation error; got {:?}",
        roots
            .iter()
            .map(|e| (e.node_id, e.source, &e.error_text))
            .collect::<Vec<_>>()
    );
    assert_eq!(roots[0].source, APIErrorSource::Validation);
    assert_eq!(roots[0].node_id, Some(head));

    // The poisoned node contributes no eval row (D8), and the downstream entry
    // collapses behind the node it addresses.
    assert!(
        !errors
            .iter()
            .any(|e| e.node_id == Some(head) && e.source == APIErrorSource::Evaluation),
        "the synthesized entry must stay deduped away"
    );
    let derived = row_for_node(&errors, middle, APIErrorSource::Evaluation);
    let root = derived.root_cause.as_ref().expect("middle is derived");
    assert_eq!(root.node_id, head);
}

/// Two independent failures are two independent problems: each is its own
/// top-level row, and each downstream cone collapses behind its own root.
#[test]
fn independent_failures_are_separate_roots() {
    let mut designer = setup_designer_with_network("main");
    let source_a = add_expr(&mut designer, "x + 1", &["x"]);
    let sink_a = add_expr(&mut designer, "p + 1", &["p"]);
    let source_b = add_expr(&mut designer, "y + 1", &["y"]);
    let sink_b = add_expr(&mut designer, "q + 1", &["q"]);
    designer.connect_nodes(source_a, 0, sink_a, 0);
    designer.connect_nodes(source_b, 0, sink_b, 0);
    designer.set_node_display(sink_a, true);
    designer.set_node_display(sink_b, true);
    validate_and_refresh(&mut designer);

    let errors = errors_of(&designer, "main");
    let mut root_ids: Vec<u64> = top_level_rows(&errors)
        .iter()
        .filter_map(|e| e.node_id)
        .collect();
    root_ids.sort_unstable();
    let mut expected = vec![source_a, source_b];
    expected.sort_unstable();
    assert_eq!(root_ids, expected, "both sources are top-level roots");

    assert_eq!(
        row_for_node(&errors, sink_a, APIErrorSource::Evaluation)
            .root_cause
            .as_ref()
            .map(|r| r.node_id),
        Some(source_a)
    );
    assert_eq!(
        row_for_node(&errors, sink_b, APIErrorSource::Evaluation)
            .root_cause
            .as_ref()
            .map(|r| r.node_id),
        Some(source_b)
    );
}

/// Links are recorded at **wire resolution**, so they cover consumers that
/// merely pass an upstream error through — a lazy selector like `if` never
/// wraps the error in text of its own, yet its entry is still classified as
/// derived and points at the failure it forwarded.
#[test]
fn origins_are_recorded_for_a_pass_through_consumer() {
    let mut designer = setup_designer_with_network("main");
    let cond = designer.add_node("bool", DVec2::ZERO);
    let failing = add_expr(&mut designer, "x + 1", &["x"]);
    let selector = designer.add_node("if", DVec2::new(200.0, 0.0));
    designer.connect_nodes(cond, 0, selector, 0);
    // Both branches fail, so the link is recorded whichever one `if` takes.
    designer.connect_nodes(failing, 0, selector, 1);
    designer.connect_nodes(failing, 0, selector, 2);
    designer.set_node_display(selector, true);
    validate_and_refresh(&mut designer);

    let errors = errors_of(&designer, "main");
    let roots = top_level_rows(&errors);
    assert_eq!(
        roots.len(),
        1,
        "the forwarded error is one problem, not two; got {:?}",
        roots
            .iter()
            .map(|e| (e.node_id, &e.error_text))
            .collect::<Vec<_>>()
    );
    assert_eq!(roots[0].node_id, Some(failing));
    assert_eq!(
        row_for_node(&errors, selector, APIErrorSource::Evaluation)
            .root_cause
            .as_ref()
            .map(|r| r.node_id),
        Some(failing),
        "a pass-through consumer is derived, like a wrapping one"
    );
}

